#!/usr/bin/env python3
"""Generate separate AUR -bin recipes from a release's SHA256SUMS (no credentials)."""
import argparse
import hashlib
from pathlib import Path
import re
import shlex
import shutil
from package import ROOT, COMMON, GUI, contents


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--version', required=True)
    parser.add_argument('--checksums', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    if not re.fullmatch(r'\d+\.\d+\.\d+', args.version):
        parser.error('version must be X.Y.Z')
    checksums = {}
    for line in args.checksums.read_text().splitlines():
        match = re.fullmatch(r'([0-9a-f]{64})\s+\*?([^/\s]+)', line)
        if not match:
            parser.error('invalid SHA256SUMS line')
        sha, name = match.groups()
        if name in checksums:
            parser.error(f'duplicate checksum: {name}')
        checksums[name] = sha
    for kind in ('gui', 'cli'):
        for rid in ('linux-x64', 'linux-arm64'):
            if f'omnilyrics-{kind}-{rid}.zip' not in checksums:
                parser.error(f'missing {kind} {rid} release checksum')
    for kind in ('gui', 'cli'):
        name = 'omnilyrics' if kind == 'gui' else 'omnilyrics-cli'
        pkgname = name + '-bin'
        out = args.output / pkgname
        if out.exists():
            parser.error(f'refusing to overwrite {out}')
        out.mkdir(parents=True)
        deps = COMMON['archlinux'] + (GUI['archlinux'] if kind == 'gui' else [])
        desc = 'Desktop lyrics with karaoke highlighting' if kind == 'gui' else 'Terminal lyrics and interactive settings'
        binary = f'OmniLyrics.{kind.title()}'
        files = contents(kind)
        sources, sums = [], []
        for src, dst in files:
            local = Path(src).name
            shutil.copyfile(ROOT / src, out / local)
            sources.append(local)
            sums.append(hashlib.sha256((out / local).read_bytes()).hexdigest())
        arch_sources = {
            arch: f'omnilyrics-{kind}-{args.version}-{arch}.zip::https://github.com/zzxzzk115/OmniLyrics/releases/download/v{args.version}/omnilyrics-{kind}-{rid}.zip'
            for arch, rid in [('x86_64', 'linux-x64'), ('aarch64', 'linux-arm64')]
        }
        arch_sums = {arch: checksums[f'omnilyrics-{kind}-{rid}.zip']
                     for arch, rid in [('x86_64', 'linux-x64'), ('aarch64', 'linux-arm64')]}
        arrays = {'arch': ['x86_64', 'aarch64'], 'license': ['MIT'], 'depends': deps,
                  'provides': [name], 'conflicts': [name], 'options': ['!strip', '!debug'],
                  'source': sources, 'sha256sums': sums}
        for arch in arch_sources:
            arrays['source_' + arch] = [arch_sources[arch]]
            arrays['sha256sums_' + arch] = [arch_sums[arch]]
        recipe = ['# Maintainer: Lazy_V <33739170+zzxzzk115@users.noreply.github.com>',
                  '# Generated by build/linux/make-aur.py; refresh using the release SHA256SUMS.',
                  f'pkgname={pkgname}', f'pkgver={args.version}', 'pkgrel=1',
                  'pkgdesc=' + shlex.quote(desc), "url='https://github.com/zzxzzk115/OmniLyrics'"]
        recipe += [key + '=(' + ' '.join(shlex.quote(x) for x in values) + ')' for key, values in arrays.items()]
        recipe += ['', 'package() {', f'  install -Dm755 "$srcdir/{binary}" "$pkgdir/usr/lib/{name}/{binary}"',
                   '  install -d "$pkgdir/usr/bin"', f'  ln -s /usr/lib/{name}/{binary} "$pkgdir/usr/bin/{name}"']
        recipe += [f'  install -Dm644 "$srcdir/{Path(src).name}" "$pkgdir{dst}"' for src, dst in files]
        recipe += ['}', '']
        (out / 'PKGBUILD').write_text('\n'.join(recipe))
        info = [f'pkgbase = {pkgname}', f'\tpkgdesc = {desc}', f'\tpkgver = {args.version}', '\tpkgrel = 1',
                '\turl = https://github.com/zzxzzk115/OmniLyrics']
        for key, values in arrays.items():
            info += [f'\t{key} = {value}' for value in values]
        info += ['', f'pkgname = {pkgname}', '']
        (out / '.SRCINFO').write_text('\n'.join(info))
        print(f'Generated {out}')


if __name__ == '__main__':
    main()
